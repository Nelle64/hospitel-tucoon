import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Img, scaleNN } from './canvas';
import { packAtlas, phaserJSON, type Atlas } from './build-atlas';
import { generateTiles } from './generate-tiles';
import { generateFurniture, FURNITURE_SIZES } from './generate-furniture';
import { ACCESSORIES, CHAR_H, CHAR_W, DIRS, FRAMES_PER_DIR, HAIR_STYLES, LIE_FRAME, OUTFITS, ROLE_ACCESSORY, STRIP_FRAMES, composePreview, generateCharacters } from './generate-characters';
import { appIcon, generateEffects } from './generate-effects';
import { generateAudio } from './generate-audio';
import { HAIR, SKIN } from './palette';
import { LAYOUT_DECOR, LAYOUT_MODULES } from '../../src/systems/layout';

const OUT = 'public/assets';
const ICONS = 'public/icons';
const DOCS = 'docs/images';
mkdirSync(OUT, { recursive: true });
mkdirSync(join(OUT, 'audio'), { recursive: true });
mkdirSync(ICONS, { recursive: true });
mkdirSync(DOCS, { recursive: true });

const t0 = Date.now();
const groups = {
  tiles: generateTiles(),
  furniture: generateFurniture(),
  chars: generateCharacters(),
  fx: generateEffects(),
};
const atlases: Atlas[] = [
  packAtlas('tiles', groups.tiles, 512),
  packAtlas('furniture', groups.furniture, 1024),
  packAtlas('chars', groups.chars, 1400),
  packAtlas('fx', groups.fx, 512),
];
const manifestFrames: Record<string, { atlas: string; w: number; h: number; usage: string }> = {};
const errors: string[] = [];
for (const a of atlases) {
  const file = `atlas-${a.name}.png`;
  const png = a.img.toPNG();
  writeFileSync(join(OUT, file), png);
  writeFileSync(join(OUT, `atlas-${a.name}.json`), JSON.stringify(phaserJSON(a, file)));
  // Validation: decodes, frames inside bounds, non-empty.
  const decoded = Img.fromPNG(png);
  if (decoded.w !== a.img.w || decoded.h !== a.img.h) errors.push(`${file} corrupt`);
  const group = groups[a.name as keyof typeof groups];
  for (const s of group) {
    const f = a.frames[s.name]!;
    if (f.x < 0 || f.y < 0 || f.x + f.w > a.img.w || f.y + f.h > a.img.h) errors.push(`${s.name} outside atlas`);
    if (s.img.opaqueCount() === 0) errors.push(`${s.name} is empty`);
    manifestFrames[s.name] = { atlas: a.name, w: f.w, h: f.h, usage: s.usage };
  }
}
// Every sprite referenced by room layouts must exist with the declared footprint.
for (const [room, m] of Object.entries(LAYOUT_MODULES)) for (const it of m.items) {
  if (!manifestFrames[it.sprite]) errors.push(`room ${room} references missing sprite ${it.sprite}`);
  else if (FURNITURE_SIZES[it.sprite]![0] !== it.w || FURNITURE_SIZES[it.sprite]![1] !== it.h) errors.push(`sprite ${it.sprite} size mismatch for ${room}`);
}
for (const [room, list] of Object.entries(LAYOUT_DECOR)) for (const s of list) if (!manifestFrames[s]) errors.push(`room ${room} decor references missing sprite ${s}`);
for (const id of Object.keys(LAYOUT_MODULES)) {
  if (!manifestFrames[`floor_${id}`]) errors.push(`missing floor_${id}`);
  if (!manifestFrames[`room_${id}`]) errors.push(`missing room icon ${id}`);
}
// Character strips must have identical frame layout.
for (const s of groups.chars) if (s.img.w !== CHAR_W * STRIP_FRAMES || s.img.h !== CHAR_H) errors.push(`character strip ${s.name} has wrong size`);

// Audio
const audio = generateAudio();
for (const a of audio) writeFileSync(join(OUT, 'audio', `${a.name}.wav`), a.data);

// App icons
const base = appIcon(false);
const mask = appIcon(true);
writeFileSync(join(ICONS, 'icon-192.png'), scaleNN(base, 3).toPNG());
writeFileSync(join(ICONS, 'icon-512.png'), scaleNN(base, 8).toPNG());
writeFileSync(join(ICONS, 'icon-maskable-512.png'), scaleNN(mask, 8).toPNG());
writeFileSync(join(ICONS, 'apple-touch-icon.png'), scaleNN(base, 3).toPNG());

// CSS sprites for DOM UI icons (from the fx atlas), 1× and 2×.
const fx = atlases.find((a) => a.name === 'fx')!;
let css = `/* Generated by tools/generate-assets – do not edit. */\n.ico{display:inline-block;background-image:url(atlas-fx.png);background-repeat:no-repeat;image-rendering:pixelated;flex:none}\n`;
css += `.ico{width:48px;height:48px;background-size:${fx.img.w * 2}px ${fx.img.h * 2}px}\n.ico.s1{width:24px;height:24px;background-size:${fx.img.w}px ${fx.img.h}px}\n.ico.s16{width:32px;height:32px;background-size:${fx.img.w * 2}px ${fx.img.h * 2}px}\n`;
for (const [name, f] of Object.entries(fx.frames)) {
  css += `.ico.i-${name}{background-position:-${f.x * 2}px -${f.y * 2}px;width:${f.w * 2}px;height:${f.h * 2}px}\n`;
  css += `.ico.s1.i-${name}{background-position:-${f.x}px -${f.y}px;width:${f.w}px;height:${f.h}px}\n`;
}
writeFileSync(join(OUT, 'ui-icons.css'), css);

const manifest = {
  generatedBy: 'tools/generate-assets/index.ts',
  tileSize: 32,
  atlases: atlases.map((a) => ({ name: a.name, image: `atlas-${a.name}.png`, json: `atlas-${a.name}.json`, width: a.img.w, height: a.img.h, frames: Object.keys(a.frames).length })),
  frames: manifestFrames,
  characters: { frameW: CHAR_W, frameH: CHAR_H, framesPerDir: FRAMES_PER_DIR, dirs: DIRS, lieFrame: LIE_FRAME, stripFrames: STRIP_FRAMES, skins: SKIN.length, hairStyles: HAIR_STYLES, hairColors: HAIR.length, outfits: OUTFITS.map((o) => o.id), accessories: ACCESSORIES, roleAccessory: ROLE_ACCESSORY },
  audio: audio.map((a) => ({ name: a.name, file: `audio/${a.name}.wav`, usage: a.usage, priority: a.priority, category: a.category, seconds: a.seconds })),
};
writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 1));

// Documentation previews: atlas overview + character sample sheet.
const previews: Img[] = [];
for (let k = 0; k < 16; k++) {
  const layers = [groups.chars.find((s) => s.name === `skin_${k % 4}`)!.img, groups.chars.find((s) => s.name === `outfit_${OUTFITS[k % OUTFITS.length]!.id}`)!.img, groups.chars.find((s) => s.name === `hair_${HAIR_STYLES[k % 6]}_${(k * 5) % 6}`)!.img];
  const acc = ROLE_ACCESSORY[OUTFITS[k % OUTFITS.length]!.id];
  if (acc) layers.push(groups.chars.find((s) => s.name === `acc_${acc}`)!.img);
  previews.push(composePreview(layers));
}
const sheet = new Img(CHAR_W * STRIP_FRAMES, CHAR_H * previews.length);
previews.forEach((p, i) => sheet.draw(p, 0, i * CHAR_H));
writeFileSync(join(DOCS, 'characters-preview.png'), scaleNN(sheet, 2).toPNG());
const ov = atlases.filter((a) => a.name !== 'chars');
const ovW = ov.reduce((s, a) => s + a.img.w + 8, 0);
const ovH = Math.max(...ov.map((a) => a.img.h));
const overview = new Img(ovW, ovH);
overview.rect(0, 0, ovW, ovH, [40, 44, 60, 255]);
let ox = 0;
for (const a of ov) {
  overview.draw(a.img, ox, 0);
  ox += a.img.w + 8;
}
writeFileSync(join(DOCS, 'atlas-overview.png'), overview.toPNG());

const count = Object.keys(manifestFrames).length;
console.log(`assets: ${count} sprites in ${atlases.length} atlases, ${audio.length} sounds, ${Date.now() - t0} ms`);
for (const a of atlases) console.log(`  atlas-${a.name}.png ${a.img.w}×${a.img.h} (${Object.keys(a.frames).length} frames)`);
if (errors.length) {
  for (const e of errors) console.error(`  ✗ ${e}`);
  process.exit(1);
}
console.log('  ✓ asset validation passed');
